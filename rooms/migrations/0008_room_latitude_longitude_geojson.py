# Approximate map locations for existing geo chats (network_group_id like geo_*).
# Coordinates are WGS84; GeoJSON rings are [longitude, latitude].
# Polygons are stored on Room.geojson; the people map currently shows markers only.


def _close(ring):
    coords = [list(point) for point in ring]
    if coords[0] != coords[-1]:
        coords.append(list(coords[0]))
    return coords


def polygon(*points):
    return {"type": "Polygon", "coordinates": [_close(points)]}


def multi_polygon(*polygons):
    return {
        "type": "MultiPolygon",
        "coordinates": [item["coordinates"] for item in polygons],
    }


def circle(lng, lat, km, points=24):
    """Approximate a coverage blob around a city as a regular polygon."""
    ring = []
    for i in range(points):
        angle = 2 * math.pi * i / points
        ring.append((
            lng + (km / (111.32 * math.cos(math.radians(lat)))) * math.sin(angle),
            lat + (km / 110.57) * math.cos(angle),
        ))
    return polygon(*ring)


def geojson_for_location(location):
    if location.get("geojson"):
        return location["geojson"]
    return circle(location["longitude"], location["latitude"], location.get("circle_km", 40))


